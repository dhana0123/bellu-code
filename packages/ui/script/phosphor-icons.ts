const assets = path.join(path.dirname(Bun.resolveSync("@phosphor-icons/core/package.json", import.meta.dir)), "assets", "duotone")
const missing: string[] = []
const entries: string[] = []
for (const [name, phosphor] of Object.entries(map)) {
  const file = Bun.file(path.join(assets, `${phosphor}-duotone.svg`))
  if (!(await file.exists())) {
    missing.push(`${name} → ${phosphor}`)
    continue
  }
  const svg = await file.text()
  // Keep the inner markup; the Icon component supplies the <svg> element and its viewBox.
  const body = svg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").replace(/`/g, "")
  entries.push(`  ${JSON.stringify(name)}: \`${body}\`,`)
}
if (missing.length) throw new Error(`Unknown Phosphor icons:\n${missing.join("\n")}`)

await Bun.write(
  path.join(import.meta.dir, "..", "src", "icons", "phosphor-icons.ts"),
  `// Generated by script/phosphor-icons.ts from @phosphor-icons/core (MIT, duotone weight). Do not edit by hand.
export const phosphorViewBox = "0 0 256 256"

export const phosphorIcons = {
${entries.join("\n")}
} as const
`,
)
console.log(`wrote ${entries.length} icons`)
