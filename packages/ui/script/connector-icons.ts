// Generates src/icons/connector-logos.ts: brand logos for the connector cards.
// Sources: simple-icons (CC0-1.0) for most brands; devicon (MIT) for AWS and Azure, which simple-icons no longer ships.
// Run `bun script/connector-icons.ts` from packages/ui after changing the maps. The logos only identify the service;
// each mark remains the trademark of its owner.
import path from "node:path"
import * as simple from "simple-icons"

// Connector icon id → simple-icons export name.
const simpleMap = {
  cloudflare: "siCloudflare",
  github: "siGithub",
  gitlab: "siGitlab",
  bitbucket: "siBitbucket",
  kubernetes: "siKubernetes",
  "google-cloud": "siGooglecloud",
  sentry: "siSentry",
  mongodb: "siMongodb",
  railway: "siRailway",
  render: "siRender",
  supabase: "siSupabase",
} as const satisfies Record<string, keyof typeof simple>

// Connector icon id → devicon file (relative to icons/).
const deviconMap = {
  aws: "amazonwebservices/amazonwebservices-original.svg",
  azure: "azure/azure-plain.svg",
} as const
// The plain Azure glyph is gray; draw it in the official Azure blue.
const deviconColor: Record<string, string> = { azure: "#0078D4" }

type Path = { d: string; fill: string }
// Dark brand colors turn into currentColor so they stay legible on a dark background.
const adapt = (hex: string) => {
  const value = hex.replace("#", "")
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(value.slice(i, i + 2), 16) / 255)
  const luminance = 0.2126 * r! + 0.7152 * g! + 0.0722 * b!
  return luminance < 0.25 ? "currentColor" : `#${value.toUpperCase()}`
}

const logos: Record<string, { viewBox: string; paths: Path[] }> = {}
for (const [id, name] of Object.entries(simpleMap)) {
  const icon = simple[name]
  logos[id] = { viewBox: "0 0 24 24", paths: [{ d: icon.path, fill: adapt(icon.hex) }] }
}
const devicon = path.join(path.dirname(Bun.resolveSync("devicon/package.json", import.meta.dir)), "icons")
for (const [id, file] of Object.entries(deviconMap)) {
  const svg = await Bun.file(path.join(devicon, file)).text()
  const paths = [...svg.matchAll(/<path\b[^>]*>/g)].map((match) => {
    const tag = match[0]
    const d = tag.match(/\sd="([^"]+)"/)?.[1]
    if (!d) throw new Error(`${id}: path without d`)
    return { d, fill: adapt(deviconColor[id] ?? tag.match(/\sfill="([^"]+)"/)?.[1] ?? "") }
  })
  logos[id] = { viewBox: svg.match(/viewBox="([^"]+)"/)![1]!, paths }
}

const entries = Object.keys(logos)
  .sort()
  .map((id) => `  ${JSON.stringify(id)}: ${JSON.stringify(logos[id])},`)
await Bun.write(
  path.join(import.meta.dir, "..", "src", "icons", "connector-logos.ts"),
  `// Generated by script/connector-icons.ts from simple-icons (CC0-1.0) and devicon (MIT). Do not edit by hand.
// Brand logos identify the service only; each mark is the trademark of its owner.
export const connectorLogos = {
${entries.join("\n")}
} as const
`,
)
console.log(`wrote ${entries.length} logos`)
