import type { Connectors } from "@bellucode/schema/connectors"
import { createEffect, createSignal, createUniqueId, For, Match, onCleanup, Show, Switch } from "solid-js"
import { createStore } from "solid-js/store"
import { writeClipboard } from "@bellucode/session-ui/copy"
import { Button } from "@bellucode/ui/button"
import { TextField } from "@bellucode/ui/text-field"
import { useLanguage } from "@/runtime/i18n/language"
import { usePlatform } from "@/runtime/platform/platform"
import { CLIENT_HEADERS, createConnectorsData } from "./data"
import { failureMessage } from "./errors"
import { clearCredentials } from "./machine"
import {
  AWS_REGIONS,
  ROTATION_REMINDER_DAYS,
  buildCredential,
  buildParams,
  canSubmit,
  toggleRegion,
  type AwsMethod,
} from "./aws-form"
import { ConnectedStep, WizardSteps } from "./github-panel"
import {
  INITIAL_AWS_WIZARD_STATE,
  selectAwsCanGoBack,
  selectAwsWizardStep,
  transitionAwsWizard,
  type AwsWizardEvent,
} from "./aws-wizard"
import "./aws-panel.css"

export type AwsPanelProps = {
  /** The Account_Alias the connect dialog collected. The dialog validates it; the service validates it again. */
  alias: string
  /** The Auth_Config chosen in the dialog; omitted selects the connector default. */
  authConfigId?: string
  /** Disables Connect while the service is offline or the dialog is busy elsewhere. */
  disabled?: boolean
  /** Called with the new Connection once the service accepted and verified it. */
  onDone: (connection: Connectors.Connection) => void
  onCancel: () => void
}

type Template = "cloudformation" | "terraform"
type Copy = "idle" | "copied" | "unavailable"
type CopyTarget = "externalId" | "template" | "terraform"

const COPY_FEEDBACK_MS = 2000
const AWS_DOCS_URL = "https://github.com/dhana0123/bellu-code/blob/bellu-graph-native/docs/connectors/aws/README.md"
const TERRAFORM_DOCS_URL = "https://registry.terraform.io/providers/hashicorp/aws/latest/docs"

export function AwsPanel(props: AwsPanelProps) {
  const language = useLanguage()
  const platform = usePlatform()
  const data = createConnectorsData()
  const connect = data.createMutation()
  const setup = data.createMutation()
  const id = createUniqueId()

  const [form, setForm] = createStore({
    method: "assume_role" as AwsMethod,
    roleArn: "",
    regions: [] as string[],
    /** The missing-region message shows only after the user has touched the selection. */
    regionsTouched: false,
    accessKeyId: "",
    secretAccessKey: "",
    sessionToken: "",
    reminder: false,
  })
  const [view, setView] = createStore({
    template: "cloudformation" as Template,
    copy: "idle" as Copy,
    copied: undefined as CopyTarget | undefined,
    connected: undefined as Connectors.Connection | undefined,
    setup: undefined as Connectors.AwsSetup | undefined,
  })

  // AssumeRole always uses the server's own AWS identity; the vault source is no longer offered.
  const model = () => ({ ...form, source: "ambient" as const, regions: form.regions, externalId: view.setup?.externalId ?? "" })
  const submittable = () => !props.disabled && !connect.busy() && canSubmit(model())
  const regionsMissing = () => form.regionsTouched && form.regions.length === 0
  const [wizard, setWizard] = createSignal(INITIAL_AWS_WIZARD_STATE)
  const dispatch = (event: AwsWizardEvent) => setWizard((previous) => transitionAwsWizard(previous, event))
  const step = () => selectAwsWizardStep(wizard())
  const quickCreateUrl = () => {
    const url = view.setup?.quickCreateUrl
    return url?.startsWith("https://") ? url : undefined
  }
  const setupReady = () => {
    if (wizard().step === "setup" && form.method === "assume_role") return true
    return form.method === "assume_role" ? form.roleArn.trim() !== "" && !!view.setup : keysFilled()
  }
  const keysFilled = () => form.accessKeyId.trim() !== "" && form.secretAccessKey !== ""

  // The external ID and templates are generated by the service, once per panel, when AssumeRole is chosen.
  const loadSetup = () =>
    void setup.run(
      (client, signal) =>
        client.awsSetup(props.alias.length >= 1 && props.alias.length <= 40 ? { alias: props.alias } : {}, { signal }),
      undefined,
    ).then((result) => {
      if (result) setView("setup", result)
    })
  createEffect(() => {
    if (form.method === "assume_role" && !view.setup && !setup.busy() && !setup.failure()) loadSetup()
  })

  let copyTimer: ReturnType<typeof setTimeout> | undefined
  onCleanup(() => clearTimeout(copyTimer))
  const copy = (text: string | undefined, target: CopyTarget) => {
    if (!text) return
    clearTimeout(copyTimer)
    // `navigator.clipboard` is missing on plain-HTTP LAN origins; the platform writer or the textarea fallback covers them.
    const write = platform.writeClipboardText
      ? platform.writeClipboardText(text).then(() => true)
      : writeClipboard(text)
    void Promise.resolve(write)
      .catch(() => false)
      .then((written) => {
        setView({ copy: written ? "copied" : "unavailable", copied: target })
        copyTimer = setTimeout(() => setView({ copy: "idle", copied: undefined }), COPY_FEEDBACK_MS)
      })
  }

  // Runs from the mutation's `finally`, so the keys leave local state after success and failure alike.
  const clearFields = () =>
    setForm(
      clearCredentials({ accessKeyId: "", secretAccessKey: "", sessionToken: "" }) as {
        accessKeyId: string
        secretAccessKey: string
        sessionToken: string
      },
    )

  const submit = async (event: SubmitEvent) => {
    event.preventDefault()
    // Enter on an earlier step moves forward; only the region step sends the request.
    if (wizard().step !== "regions") {
      if (wizard().step === "choose" || setupReady()) dispatch({ type: "continued" })
      return
    }
    if (!submittable()) return
    const input: Connectors.CreateConnectionInput = {
      alias: props.alias,
      connectorId: "aws",
      authConfigId: props.authConfigId,
      method: form.method,
      params: buildParams(model()),
      credential: buildCredential(model()),
    }
    const reminder = form.method === "static_keys" && form.reminder
    const created = await connect.run(async (client, signal) => {
      const connection = await client.createConnection(input, { signal, headers: CLIENT_HEADERS })
      if (reminder)
        return client.updateConnection({ id: connection.id, rotationIntervalDays: ROTATION_REMINDER_DAYS }, { signal })
      return connection
    }, clearFields)
    if (created) {
      setView("connected", created)
      dispatch({ type: "connected" })
    }
  }

  const copiedLabel = (target: CopyTarget, label: string) =>
    view.copy === "copied" && view.copied === target ? language.t("settings.connectors.action.copied") : label
  const steps = () =>
    form.method === "assume_role"
      ? ([
          { step: 1, key: "settings.connectors.aws.wizard.step.choose" },
          { step: 2, key: "settings.connectors.aws.wizard.step.role" },
          { step: 3, key: "settings.connectors.aws.wizard.step.arn" },
          { step: 4, key: "settings.connectors.aws.wizard.step.regions" },
        ] as const)
      : ([
          { step: 1, key: "settings.connectors.aws.wizard.step.choose" },
          { step: 2, key: "settings.connectors.aws.wizard.step.keys" },
          { step: 3, key: "settings.connectors.aws.wizard.step.regions" },
        ] as const)
  const error = () => {
    const failure = connect.failure() ?? setup.failure()
    if (!failure) return
    return { message: failureMessage(failure), root: failure.kind === "connector" && failure.code === "invalid_credential" }
  }

  const options = [
    {
      method: "assume_role",
      title: "settings.connectors.aws.wizard.role.title",
      text: "settings.connectors.aws.wizard.role.text",
    },
    {
      method: "static_keys",
      title: "settings.connectors.aws.wizard.keys.title",
      text: "settings.connectors.aws.wizard.keys.text",
    },
  ] as const

  const tabs = (
    <div role="tablist" aria-label={language.t("settings.connectors.aws.template.label")} class="aws-panel-tabs">
      <For each={["cloudformation", "terraform"] as const}>
        {(name) => (
          <button
            type="button"
            role="tab"
            id={`${id}-tab-${name}`}
            aria-selected={view.template === name}
            aria-controls={`${id}-template`}
            tabIndex={view.template === name ? 0 : -1}
            onClick={() => setView("template", name)}
            onKeyDown={(event) => {
              if (event.key !== "ArrowRight" && event.key !== "ArrowLeft") return
              event.preventDefault()
              const next = name === "cloudformation" ? "terraform" : "cloudformation"
              setView("template", next)
              document.getElementById(`${id}-tab-${next}`)?.focus()
            }}
          >
            {language.t(`settings.connectors.aws.template.${name}`)}
          </button>
        )}
      </For>
    </div>
  )

  const docsLink = () => (
    <a href={AWS_DOCS_URL} target="_blank" rel="noopener noreferrer" class="aws-panel-link">
      {language.t("settings.connectors.aws.wizard.docs")}
    </a>
  )

  const codeBlock = (text: () => string | undefined, target: CopyTarget) => (
    <div class="aws-panel-code">
      <pre tabIndex={0} data-scrollable>
        <code>{text()}</code>
      </pre>
      <Button size="small" variant="outline" onClick={() => copy(text(), target)}>
        {copiedLabel(target, language.t("settings.connectors.action.copy"))}
      </Button>
    </div>
  )

  const roleStep = (
    <section class="aws-panel-section">
      <p class="aws-panel-note">
        {language.t("settings.connectors.aws.wizard.intro")} {docsLink()}
      </p>
      <Show when={setup.busy()}>
        <p role="status" class="aws-panel-note">
          {language.t("settings.connectors.aws.setup.loading")}
        </p>
      </Show>
      <Show when={view.setup}>
        {(setupValue) => (
          <>
            {tabs}
            <div
              role="tabpanel"
              id={`${id}-template`}
              aria-labelledby={`${id}-tab-${view.template}`}
              class="aws-panel-template"
            >
              <Show
                when={view.template === "cloudformation"}
                fallback={
                  <>
                    {codeBlock(() => view.setup?.terraform, "terraform")}
                    <a
                      href={TERRAFORM_DOCS_URL}
                      target="_blank"
                      rel="noopener noreferrer"
                      class="aws-panel-link"
                    >
                      {language.t("settings.connectors.aws.wizard.terraformDocs")}
                    </a>
                  </>
                }
              >
                {codeBlock(() => view.setup?.cloudFormation, "template")}
                <Show when={quickCreateUrl()}>
                  {(url) => (
                    <a
                      href={url()}
                      target="_blank"
                      rel="noopener noreferrer"
                      data-component="button-v2"
                      data-variant="submit"
                      data-size="small"
                      data-slot="aws-launch-stack"
                    >
                      {language.t("settings.connectors.aws.wizard.launch")}
                    </a>
                  )}
                </Show>
              </Show>
            </div>
            <div class="aws-panel-external">
              <span>{language.t("settings.connectors.aws.externalId")}</span>
              <code>{setupValue().externalId}</code>
              <Button
                size="small"
                variant="ghost"
                aria-label={`${language.t("settings.connectors.action.copy")}: ${language.t("settings.connectors.aws.externalId")}`}
                onClick={() => copy(setupValue().externalId, "externalId")}
              >
                {copiedLabel("externalId", language.t("settings.connectors.action.copy"))}
              </Button>
            </div>
          </>
        )}
      </Show>
      <p role="status" class="aws-panel-note" data-tone="warning">
        <Show when={view.copy === "unavailable"}>{language.t("settings.connectors.aws.template.copyUnavailable")}</Show>
      </p>
    </section>
  )

  const arnStep = (
    <section class="aws-panel-section">
      <p class="aws-panel-note">{language.t("settings.connectors.aws.wizard.arn.hint")}</p>
      <TextField
        label={language.t("settings.connectors.aws.roleArn")}
        value={form.roleArn}
        onChange={(value) => setForm("roleArn", value)}
        placeholder="arn:aws:iam::123456789012:role/BelluReadOnly"
        autocomplete="off"
        spellcheck={false}
        required
      />
    </section>
  )

  const keysStep = (
    <>
      <section class="aws-panel-section">
        <TextField
          label={language.t("settings.connectors.aws.accessKeyId")}
          type="password"
          value={form.accessKeyId}
          onChange={(value) => setForm("accessKeyId", value)}
          autocomplete="off"
          spellcheck={false}
          required
        />
        <TextField
          label={language.t("settings.connectors.aws.secretAccessKey")}
          type="password"
          value={form.secretAccessKey}
          onChange={(value) => setForm("secretAccessKey", value)}
          autocomplete="off"
          spellcheck={false}
          required
        />
        <TextField
          label={language.t("settings.connectors.aws.sessionToken")}
          type="password"
          value={form.sessionToken}
          onChange={(value) => setForm("sessionToken", value)}
          autocomplete="off"
          spellcheck={false}
        />
        <label class="aws-panel-method">
          <input type="checkbox" checked={form.reminder} onChange={(event) => setForm("reminder", event.currentTarget.checked)} />
          <span>{language.t("settings.connectors.aws.rotationReminder")}</span>
        </label>
        {docsLink()}
      </section>
    </>
  )

  return (
    <form class="aws-panel" onSubmit={submit} autocomplete="off">
      <WizardSteps current={step()} steps={steps()} label={language.t("settings.connectors.aws.wizard.label")} />
      <Switch>
        <Match when={view.connected} keyed>
          {(connection) => (
            <ConnectedStep
              connection={connection}
              onDone={() => props.onDone(connection)}
              title={language.t("settings.connectors.aws.connected.title")}
              account={(account) => language.t("settings.connectors.aws.connected.account", { account })}
              note={language.t("settings.connectors.aws.connected.note")}
            />
          )}
        </Match>
        <Match when={step() === 1}>
          <fieldset data-slot="github-wizard-options">
            <legend class="sr-only">{language.t("settings.connectors.aws.methods.label")}</legend>
            <For each={options}>
              {(option) => (
                <label data-slot="github-wizard-option">
                  <input
                    type="radio"
                    name={`${id}-method`}
                    value={option.method}
                    checked={form.method === option.method}
                    onChange={() => {
                      setForm("method", option.method)
                      dispatch({ type: "method.selected", method: option.method })
                    }}
                  />
                  <span data-slot="github-wizard-option-body">
                    <span data-slot="github-wizard-option-title">{language.t(option.title)}</span>
                    <span data-slot="github-wizard-option-text">{language.t(option.text)}</span>
                  </span>
                </label>
              )}
            </For>
          </fieldset>
          <div class="aws-panel-actions">
            <Button variant="ghost" onClick={() => props.onCancel()}>
              {language.t("settings.connectors.action.cancel")}
            </Button>
            <Button type="submit" variant="submit">
              {language.t("settings.connectors.aws.wizard.continue")}
            </Button>
          </div>
        </Match>
        <Match when={wizard().step === "setup"}>
          {form.method === "assume_role" ? roleStep : keysStep}
          <div role="alert" class="aws-panel-errors">
            <Show when={setup.failure() ? error() : undefined}>
              {(current) => <p data-tone="danger">{language.t(current().message.key, current().message.params)}</p>}
            </Show>
          </div>
          <div class="aws-panel-actions">
            <Button variant="ghost" onClick={() => dispatch({ type: "back" })}>
              {language.t("settings.connectors.aws.wizard.back")}
            </Button>
            <Button type="submit" variant="submit" disabled={!setupReady()}>
              {language.t("settings.connectors.aws.wizard.continue")}
            </Button>
          </div>
        </Match>
        <Match when={wizard().step === "arn"}>
          {arnStep}
          <div class="aws-panel-actions">
            <Button variant="ghost" onClick={() => dispatch({ type: "back" })}>
              {language.t("settings.connectors.aws.wizard.back")}
            </Button>
            <Button type="submit" variant="submit" disabled={!setupReady()}>
              {language.t("settings.connectors.aws.wizard.continue")}
            </Button>
          </div>
        </Match>
        <Match when={wizard().step === "regions"}>
          <fieldset class="aws-panel-regions" aria-describedby={regionsMissing() ? `${id}-regions-error` : undefined} disabled={connect.busy()}>
            <legend>{language.t("settings.connectors.aws.regions")}</legend>
            <For each={AWS_REGIONS}>
              {(region) => (
                <label class="aws-panel-method">
                  <input
                    type="checkbox"
                    checked={form.regions.includes(region)}
                    onChange={() => setForm({ regions: toggleRegion(form.regions, region), regionsTouched: true })}
                  />
                  <code>{region}</code>
                </label>
              )}
            </For>
            <p id={`${id}-regions-error`} role="alert" class="aws-panel-note" data-tone="danger">
              <Show when={regionsMissing()}>{language.t("settings.connectors.aws.regions.required")}</Show>
            </p>
          </fieldset>
          <div role="alert" class="aws-panel-errors">
            <Show when={error()}>
              {(current) => (
                <>
                  <p data-tone="danger">{language.t(current().message.key, current().message.params)}</p>
                  <Show when={current().root}>
                    <p data-tone="danger">{language.t("settings.connectors.aws.rootRejected")}</p>
                  </Show>
                </>
              )}
            </Show>
          </div>
          <div class="aws-panel-actions">
            <Button variant="ghost" disabled={!selectAwsCanGoBack(wizard(), connect.busy())} onClick={() => dispatch({ type: "back" })}>
              {language.t("settings.connectors.aws.wizard.back")}
            </Button>
            <Button type="submit" variant="submit" disabled={!submittable()}>
              {language.t(
                form.method === "assume_role"
                  ? "settings.connectors.aws.wizard.verify"
                  : "settings.connectors.action.connect",
              )}
            </Button>
          </div>
        </Match>
      </Switch>
    </form>
  )
}
