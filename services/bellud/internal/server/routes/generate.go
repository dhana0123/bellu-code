package routes

import (
	"fmt"
	"sort"
	"strings"
)

// OperationInfo is one entry of testdata/operations.json, written by
// script/gen-operations.ts from the TS Api OpenAPI document.
type OperationInfo struct {
	Method      string `json:"method"`
	Path        string `json:"path"`
	OperationID string `json:"operationId"`
	Group       string `json:"group"`
	Stream      bool   `json:"stream"`
}

// Operations converts the operation list to validation input.
func Operations(infos []OperationInfo) []Operation {
	ops := make([]Operation, len(infos))
	for i, o := range infos {
		ops[i] = Operation{Method: o.Method, Path: o.Path}
	}
	return ops
}

// goOwnedPrefixes lists path prefixes whose protocol operations are served by
// the Go server (declared in TS for the contract only). Req 2.5 (registered
// handler plus passing contract test) is enforced separately.
var goOwnedPrefixes = []string{"/api/experimental/graph/"}

func goOwned(path string) bool {
	for _, p := range goOwnedPrefixes {
		if strings.HasPrefix(path, p) {
			return true
		}
	}
	return false
}

// GenerateRoutes builds the initial table: every protocol operation owned by
// ts, plus the web shell entries mirroring packages/cli/src/services/web-ui.ts.
// Only /auth/* and the web shell are public; an unlisted /api path falls to a
// non-public ts entry so the shell catch-all never exposes API paths.
func GenerateRoutes(infos []OperationInfo) []Route {
	routes := make([]Route, 0, len(infos)+4)
	for _, o := range infos {
		owner := OwnerTS
		if goOwned(o.Path) {
			owner = OwnerGo
		}
		routes = append(routes, Route{
			Method:  o.Method,
			Pattern: o.Path,
			Group:   o.Group,
			Owner:   owner,
			Public:  o.Path == "/auth" || strings.HasPrefix(o.Path, "/auth/"),
			Stream:  o.Stream,
		})
	}
	routes = append(routes,
		// The MCP endpoint is not an HttpApi operation but is served by Go.
		Route{Method: "*", Pattern: "/api/experimental/graph/mcp", Group: "experimental", Owner: OwnerGo, Stream: true},
		Route{Method: "*", Pattern: "/api", Group: "api", Owner: OwnerTS},
		Route{Method: "*", Pattern: "/api/*", Group: "api", Owner: OwnerTS},
		Route{Method: "*", Pattern: "/auth/*", Group: "auth", Owner: OwnerTS, Public: true},
		Route{Method: "GET", Pattern: "/openapi.json", Group: "openapi", Owner: OwnerTS, Public: true},
		Route{Method: "*", Pattern: "/", Group: "web", Owner: OwnerTS, Public: true},
		Route{Method: "*", Pattern: "/*", Group: "web", Owner: OwnerTS, Public: true},
	)
	sort.SliceStable(routes, func(i, j int) bool {
		if routes[i].Pattern != routes[j].Pattern {
			return routes[i].Pattern < routes[j].Pattern
		}
		return routes[i].Method < routes[j].Method
	})
	return routes
}

// MarshalRoutes renders routes.yaml deterministically.
func MarshalRoutes(routes []Route) []byte {
	var b strings.Builder
	b.WriteString("# Generated by `go test ./internal/server/routes -run TestGenerate -update` from testdata/operations.json.\n")
	b.WriteString("# Flip an owner to go only when its handler is registered and its contract test is green.\n")
	b.WriteString("version: 1\nroutes:\n")
	for _, r := range routes {
		fmt.Fprintf(&b, "  - method: %q\n    pattern: %q\n    group: %s\n    owner: %s\n    public: %t\n    stream: %t\n",
			r.Method, r.Pattern, r.Group, r.Owner, r.Public, r.Stream)
	}
	return []byte(b.String())
}
