// Command gen reads the `redaction` section of bellu.yaml and writes
// patterns.go for package redact. Bellud has no runtime dependency on the
// bellu-ai-cyber repository; the patterns are compiled in at generation time.
//
// On any error (including a pattern that fails to compile) the existing output
// file is left unchanged and the error names the offending rule id.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"gopkg.in/yaml.v3"
)

type config struct {
	Redaction struct {
		KeyPatterns []string `yaml:"key_patterns"`
		JSONPaths   []string `yaml:"json_paths"`
	} `yaml:"redaction"`
}

type keyRule struct{ ID, Pattern string }
type pathRule struct {
	ID, Path string
	Segments []string
}

func main() {
	in := flag.String("in", "/home/ubuntu/bellu-ai-cyber/bellu.yaml", "path to bellu.yaml")
	out := flag.String("out", "patterns.go", "generated Go file")
	flag.Parse()
	if err := run(*in, *out); err != nil {
		fmt.Fprintln(os.Stderr, "redact/gen:", err)
		os.Exit(1)
	}
}

func run(in, out string) error {
	raw, err := os.ReadFile(in)
	if err != nil {
		return err
	}
	var cfg config
	if err := yaml.Unmarshal(raw, &cfg); err != nil {
		return fmt.Errorf("parse %s: %w", in, err)
	}
	src, err := render(cfg)
	if err != nil {
		return err
	}
	return writeAtomic(out, src)
}

func render(cfg config) ([]byte, error) {
	used := map[string]bool{}
	var keys []keyRule
	for _, p := range cfg.Redaction.KeyPatterns {
		id := uniqueID("key_"+slug(p), used)
		if _, err := regexp.Compile(p); err != nil {
			return nil, fmt.Errorf("rule %s: pattern %q does not compile: %w", id, p, err)
		}
		keys = append(keys, keyRule{id, p})
	}
	var paths []pathRule
	for _, p := range cfg.Redaction.JSONPaths {
		id := uniqueID("path_"+slug(p), used)
		segs := strings.Split(p, ".")
		for _, s := range segs {
			if s == "" {
				return nil, fmt.Errorf("rule %s: json path %q has an empty segment", id, p)
			}
		}
		paths = append(paths, pathRule{id, p, segs})
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by internal/redact/gen from bellu.yaml; DO NOT EDIT.\n\n")
	b.WriteString("package redact\n\nimport \"regexp\"\n\n")
	b.WriteString("// KeyRule matches JSON object keys; rules are in bellu.yaml order.\n")
	b.WriteString("type KeyRule struct {\n\tID      string\n\tPattern string\n\tRe      *regexp.Regexp\n}\n\n")
	b.WriteString("// PathRule matches dotted JSON paths; a \"*\" segment matches any one segment.\n")
	b.WriteString("type PathRule struct {\n\tID       string\n\tPath     string\n\tSegments []string\n}\n\n")
	b.WriteString("// KeyRules are the key_patterns of the redaction section.\nvar KeyRules = []KeyRule{\n")
	for _, k := range keys {
		fmt.Fprintf(&b, "\t{ID: %q, Pattern: %q, Re: regexp.MustCompile(%q)},\n", k.ID, k.Pattern, k.Pattern)
	}
	b.WriteString("}\n\n// PathRules are the json_paths of the redaction section.\nvar PathRules = []PathRule{\n")
	for _, p := range paths {
		fmt.Fprintf(&b, "\t{ID: %q, Path: %q, Segments: []string{", p.ID, p.Path)
		for i, s := range p.Segments {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "%q", s)
		}
		b.WriteString("}},\n")
	}
	b.WriteString("}\n")
	formatted, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated source: %w", err)
	}
	return formatted, nil
}

var nonAlnum = regexp.MustCompile(`[^a-z0-9]+`)

// slug lower-cases s, drops a leading (?i) flag and collapses other
// punctuation runs into a single underscore.
func slug(s string) string {
	s = strings.TrimPrefix(strings.ToLower(s), "(?i)")
	s = strings.Trim(nonAlnum.ReplaceAllString(s, "_"), "_")
	if s == "" {
		return "rule"
	}
	return s
}

func uniqueID(base string, used map[string]bool) string {
	id := base
	for n := 2; used[id]; n++ {
		id = fmt.Sprintf("%s_%d", base, n)
	}
	used[id] = true
	return id
}

func writeAtomic(path string, data []byte) error {
	tmp, err := os.CreateTemp(filepath.Dir(path), ".patterns-*.tmp")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	if _, err := tmp.Write(data); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	if err := os.Chmod(tmp.Name(), 0o644); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), path)
}
